def get_city_coords(city):
    return CITY_COORDS.get(city, CITY_COORDS['Hyderabad'])


def get_locality_coords(city, locality):
    city_localities = LOCALITY_COORDS.get(city, {})
    if locality in city_localities:
        return city_localities[locality]
    loc_lower = locality.lower().strip()
    for name, coords in city_localities.items():
        if name.lower() == loc_lower or loc_lower in name.lower() or name.lower() in loc_lower:
            return coords
    return get_city_coords(city)


def get_localities_for_city(city):
    return sorted(LOCALITY_COORDS.get(city, {}).keys())


